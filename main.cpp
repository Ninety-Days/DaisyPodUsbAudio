DaisyPod hw;

/* -----------------------------------------------------------------------
 * InitCRS — lock HSI48 (the USB peripheral's clock source, per libDaisy's
 * system.cpp: UsbClockSelection = RCC_USBCLKSOURCE_HSI48) to the host's
 * own USB SOF frames in real time.
 *
 * Without this, HSI48 free-runs at its factory trim (datasheet: +/-1%,
 * i.e. up to +/-10000 ppm, with no compensation for temperature drift
 * either), completely uncorrelated with SAI's clock (HSE crystal via
 * PLL2/PLL3 -- see system.cpp's PeriphClkInitStruct.PLL2/PLL3 config).
 * Two independent, unsynchronized oscillators driving the two sides of
 * a USB-audio duplex stream is a textbook source of the kind of
 * irregular timing artifact we've been chasing -- and it's on top of,
 * not instead of, the NVIC preemption ordering (see the
 * HAL_NVIC_SetPriority calls after StartAudio() in main; usbd_conf.c
 * only sets the USB side of that ordering and cannot fix it alone).
 * The fractional Q16 drift corrector in usbd_audio_if.c absorbs slow
 * drift on the order of tens of ppm; it was never sized to absorb an
 * uncalibrated RC oscillator's much larger and less stable error.
 *
 * CRS is the STM32H7's purpose-built answer to exactly this: it uses
 * the USB SOF pulses (one every 1ms, generated by the host, i.e. the
 * actual timing authority the audio stream needs to track) as a live
 * reference to continuously trim HSI48's oscillator, typically down to
 * single-digit ppm once locked. This doesn't reconcile SAI and USB onto
 * one shared clock (they're still two separate crystals/oscillators --
 * that would need a hardware change, e.g. feeding SAI from a clock
 * derived from HSI48, which isn't how this board is wired), but it does
 * make the USB side of the equation far more accurate and stable than
 * its uncalibrated factory-trim default, which narrows the drift the
 * sigma-delta controller has to correct for down to what it was
 * actually designed to handle.
 * --------------------------------------------------------------------- */
/* Audio block size, in frames. Single source for both the buffers
   AudioCallback puts on the stack and the value main() configures, so the
   two cannot drift apart. */
#define AUDIO_BLOCK_FRAMES 48

static void InitCRS(void)
{
    __HAL_RCC_CRS_CLK_ENABLE();

    RCC_CRSInitTypeDef crs = {0};
    crs.Prescaler            = RCC_CRS_SYNC_DIV1;
    crs.Source               = RCC_CRS_SYNC_SOURCE_USB2;  /* OTG HS2 SOF --
                                       * confirmed correct. History: first
                                       * set to RCC_CRS_SYNC_SOURCE_USB1
                                       * (assumed from generic H7 examples);
                                       * crs_sync_ok_count stayed at 0 across
                                       * 60000+ polls. Chip silicon revision
                                       * was confirmed as V via
                                       * VENDOR_REQ_GET_CHIP_REV/
                                       * read_chip_rev.py, ruling out ES0392
                                       * §2.2.3 (that CRS/SOF erratum is
                                       * Y/W-only). Switched to
                                       * RCC_CRS_SYNC_SOURCE_USB2 (this
                                       * firmware's USB stack -- usbd_conf.c's
                                       * "USB_OTG_FS" instance -- resolves to
                                       * the "USB2" core on STM32H7); the
                                       * diagnostic readback still showed
                                       * SYNCSRC=2 after reflashing, which
                                       * looked like the macro wasn't taking
                                       * effect. It was a red herring: the
                                       * diagnostic code (VENDOR_REQ_GetChipRev
                                       * in usbd_audio.c) was reading
                                       * CRS->CFGR >> 14U, but SYNCSRC is
                                       * actually bits [29:28] (confirmed
                                       * against ST's official SVD via
                                       * docs.rs/stm32ral), not [15:14] --
                                       * [15:14] overlaps RELOAD[15:0]'s own
                                       * bits, and this ReloadValue
                                       * (__HAL_RCC_CRS_RELOADVALUE_CALCULATE
                                       * (48000000,1000) = 47999 = 0xBB7F)
                                       * happens to have bits [15:14] == 2,
                                       * which is exactly the "SYNCSRC=2"
                                       * every prior readback showed --
                                       * regardless of what SYNCSRC was
                                       * actually set to. The write side
                                       * (this named macro) was never the
                                       * bug; only the read/diagnostic side
                                       * was. See usbd_audio.c's
                                       * VENDOR_REQ_GetChipRev for the
                                       * corrected >> 28U read. Confirm via
                                       * read_chip_rev.py after reflashing
                                       * both fixes together: it should now
                                       * read SYNCSRC=3 (USB2) for real, and
                                       * crs_sync_ok_count in
                                       * the host diagnostics should
                                       * start climbing instead of staying
                                       * at 0. */
    crs.Polarity             = RCC_CRS_SYNC_POLARITY_RISING;
    crs.ReloadValue          = __HAL_RCC_CRS_RELOADVALUE_CALCULATE(48000000, 1000);
    crs.ErrorLimitValue      = 34;
    crs.HSI48CalibrationValue = 32;

    HAL_RCCEx_CRSConfig(&crs);
}

void AudioCallback(AudioHandle::InputBuffer in, AudioHandle::OutputBuffer out, size_t size)
{
    /* MIC/record path: push ADC samples into rec_ring so Audio_PeriodicTC
     * (the USB DataIn ISR) has something to send to the host.
     *
     * Full scale is 2^23 = 8388608.0f, not 2^15: the descriptors declare
     * bSubframeSize = 3 and the rings in usbd_audio_if.c are int32_t. */
    /* Fixed size, not int32_t buf[size * 2]. The latter is a VLA on the DMA
     * interrupt's stack: legal only as a GCC extension in C++, invisible to
     * static stack analysis, and silently proportional to whatever
     * SetAudioBlockSize() is given. At 48 frames it is 384 bytes per buffer
     * and fits; raise the block size and it grows with nothing to say so.
     * Sizing from the same constant main() configures puts the cost in the
     * map file and makes the two impossible to disagree.
     *
     * The clamp cannot fire while libDaisy hands back the size it was
     * configured with. It is here so that if it ever does not, the callback
     * drops frames rather than writing past the end of these buffers. */
    int32_t adc_in[AUDIO_BLOCK_FRAMES * 2];
    if(size > AUDIO_BLOCK_FRAMES) size = AUDIO_BLOCK_FRAMES;
    for(size_t i = 0; i < size; i++) {
        float l = in[0][i] * 8388608.0f;
        float r = in[1][i] * 8388608.0f;
        /* Clamp before truncating to int32_t: at a full-scale +1.0f
         * sample, l/r == 8388608.0f exactly, which is one past the
         * maximum representable 24-bit value (8388607) and would
         * otherwise wrap on cast -- rare (only hit exactly at a true
         * full-scale peak) but real, same reasoning as the 16-bit
         * version's +-32768/32767 guard, just at the new range. */
        if(l >  8388607.0f) l =  8388607.0f;
        if(l < -8388608.0f) l = -8388608.0f;
        if(r >  8388607.0f) r =  8388607.0f;
        if(r < -8388608.0f) r = -8388608.0f;
        adc_in[i * 2 + 0] = (int32_t)l;
        adc_in[i * 2 + 1] = (int32_t)r;
    }
    AudioIF_PushSamples(adc_in, (uint32_t)size);

    int32_t usb_in[AUDIO_BLOCK_FRAMES * 2];
    AudioIF_PopSamples(usb_in, (uint32_t)size);
    for(size_t i = 0; i < size; i++) {
        out[0][i] = (float)usb_in[i*2+0] / 8388608.0f;
        out[1][i] = (float)usb_in[i*2+1] / 8388608.0f;
    }
}

static void InitUSBAudio(void)
{
    USBD_Init(&hUsbDeviceFS, &DaisyPodUsbAudio_FS_Desc, DEVICE_FS);
    USBD_RegisterClass(&hUsbDeviceFS, &USBD_AUDIO);
    USBD_AUDIO_RegisterInterface(&hUsbDeviceFS, &USBD_AUDIO_fops);
    USBD_Start(&hUsbDeviceFS);
}

int main(void)
{
    hw.Init();
    InitCRS();
    hw.seed.SetAudioSampleRate(SaiHandle::Config::SampleRate::SAI_48KHZ);
    hw.seed.SetAudioBlockSize(AUDIO_BLOCK_FRAMES);
    InitUSBAudio();
    hw.StartAudio(AudioCallback);

    /* Interrupt priority: SAI DMA must sit below USB.
     *
     * libDaisy's dma.c sets the SAI DMA IRQs (DMA1_Stream0/1) to priority
     * (0,0) -- the SAME level as OTG_FS_IRQn in usbd_conf.c. Equal
     * priorities on Cortex-M mean NO preemption either way, so while
     * AudioCallback runs, every USB interrupt is held off for that entire
     * time. Isochronous endpoints have no retry: an IN token missed while
     * the ISR is blocked is data gone. The cheaper the callback the less
     * this shows, which is the worst way for a defect to behave.
     *
     * Scope, stated honestly: this is a defect in its own right and is
     * fixed here on that basis. It is not on its own what fixed the
     * control-pipe failure documented in usbd_conf.c -- with this change
     * alone that failure still reproduced, only later.
     *
     * Safe because all shared state is strict SPSC: pb_write/rec_read are
     * written only by USB-side ISRs, pb_read/rec_write only by the audio
     * ISR, and all indices are aligned 32-bit volatile (atomic on M7).
     *
     * Must run AFTER StartAudio(): libDaisy's DMA init (re)applies (0,0)
     * inside the audio start path, so setting this any earlier is
     * silently undone. */
    HAL_NVIC_SetPriority(DMA1_Stream0_IRQn, 2, 0); /* SAI1 A */
    HAL_NVIC_SetPriority(DMA1_Stream1_IRQn, 2, 0); /* SAI1 B */

    /* Error latch for the status LEDs. A glitch (over/underrun) is a
     * transient event -- if we only lit the LED during the one 250ms
     * window the counter moved, it would be a blink easy to miss. Instead
     * latch it: once an error is seen the LED stays red until the stream
     * is re-opened, so a fault that happened while you weren't looking is
     * still visible afterwards. */
    uint32_t last_pb_errors  = 0;
    uint32_t last_rec_errors = 0;
    uint8_t  pb_fault_latch   = 0;
    uint8_t  rec_fault_latch  = 0;

    for(;;) {
        System::Delay(250);

        /* IN-pipe stall watchdog. datain_completions advances ~1000
         * times a second whenever the host has the mic interface open,
         * so a completely frozen counter across a 250 ms window means
         * ~250 consecutive missed frames -- never normal jitter, always
         * a dead pipe. Re-arm it rather than requiring a physical
         * replug, which was the only recovery before this. Two
         * consecutive frozen windows are required, so a read that
         * happens to straddle a genuine idle moment cannot trigger it. */
        {
            static uint32_t last_datain     = 0U;
            static uint8_t  frozen_windows  = 0U;
            const  uint32_t now_datain      = datain_completions;

            if(now_datain == last_datain) {
                if(++frozen_windows >= 2U) {
                    USBD_AUDIO_KickInPipe(&hUsbDeviceFS);
                    frozen_windows = 0U;
                }
            } else {
                frozen_windows = 0U;
            }
            last_datain = now_datain;
        }

        /* --- Status LEDs -------------------------------------------
         *
         * Two-colour health at a glance. This replaces a much larger
         * block that existed to hunt a parasitic tone (now resolved); the
         * per-sample magnitude probes, zero-crossing steadiness test and
         * drift-correction wiring it used are gone with it.
         *
         * LED1 = record path (Pod -> host, the IN stream):
         *   off    idle -- host isn't reading the mic interface
         *   green  streaming cleanly
         *   red    a record underrun has occurred since the stream opened
         *
         * LED2 = playback path (host -> Pod, the OUT stream):
         *   off    idle -- gate closed, host isn't sending audio
         *   green  streaming cleanly, gate open
         *   red    a playback over/underrun has occurred since gate open
         *
         * Red latches until the relevant stream restarts, so a glitch
         * that happened while you weren't watching is still visible. The
         * blue channel is unused -- these are pure status, not level
         * meters. */
        {
            const uint8_t rec_on = AudioIF_IsRecordActive();
            const uint8_t pb_on  = AudioIF_IsPlaybackActive();

            const uint32_t rec_errors = rec_underrun_events;
            const uint32_t pb_errors  = pb_overrun_events + pb_underrun_events;

            /* Clear the latch on a fresh start (stream went from off to on
             * clears stale faults); set it when the error count moves. */
            if(rec_on && !rec_fault_latch && rec_errors != last_rec_errors)
                rec_fault_latch = 1U;
            if(!rec_on)
                rec_fault_latch = 0U;
            last_rec_errors = rec_errors;

            if(pb_on && !pb_fault_latch && pb_errors != last_pb_errors)
                pb_fault_latch = 1U;
            if(!pb_on)
                pb_fault_latch = 0U;
            last_pb_errors = pb_errors;

            /* led.Set(r, g, b). Off when idle, red on latched fault,
             * green when streaming clean. */
            hw.led1.Set(rec_on && rec_fault_latch ? 1.f : 0.f,
                        rec_on && !rec_fault_latch ? 1.f : 0.f,
                        0.f);
            hw.led2.Set(pb_on && pb_fault_latch ? 1.f : 0.f,
                        pb_on && !pb_fault_latch ? 1.f : 0.f,
                        0.f);
        }

        hw.UpdateLeds();
    }
}
