#!/usr/bin/env bash
#
# init_repo.sh — turn the publication tree into a git repository with a
# structured initial import instead of a single "initial commit".
#
# WHAT THIS DOES AND DOES NOT DO
#
# All ten commits will carry today's date. This does not fabricate a
# development history and does not try to: a reviewer will see an import,
# and backdating commits to simulate months of work would be both obvious
# from the log and dishonest.
#
# What it does give is a log where each commit is one subsystem with a
# message explaining the non-obvious decision in it. That makes the diffs
# readable per part, and it shows the author thinks in units rather than
# in one undifferentiated dump.
#
# IF YOU ALREADY HAVE A REAL GIT HISTORY from development, publish that
# instead. It is worth more than anything this script produces.
#
# Run from the root of the publication tree:
#   bash init_repo.sh
#
set -e

if [ -d .git ]; then
    echo "A .git directory already exists here. Refusing to touch it."
    echo "If you meant to start over: rm -rf .git, then run this again."
    exit 1
fi

for f in README.md LICENSE Makefile usbd_audio.c main.cpp; do
    [ -f "$f" ] || { echo "Not the publication root: $f is missing."; exit 1; }
done

git init -q

# Set these to your own identity before running, or configure them globally.
# git config user.name  "Your Name"
# git config user.email "you@example.com"

commit () { git commit -q -F -; }

git add LICENSE LICENSE-SLA0044.txt LICENSE-libDaisy-MIT.txt \
        THIRD_PARTY_NOTICES.md .gitignore
commit <<'MSG'
Licensing: MIT for own files, SLA0044 and libDaisy MIT for the rest

The repository is not single-licensed. THIRD_PARTY_NOTICES.md is the
file-by-file breakdown; most usbd_* files are ST's under SLA0044, which
forbids placing them under Open Source Terms and restricts execution to
ST silicon.
MSG

git add Makefile usbd_compat.h usbd_conf.c usbd_conf.h usbd_ctlreq.c \
        usbd_desc.c usbd_desc.h usbd_irq.c
commit <<'MSG'
Board support: PCD glue, descriptors, IRQ wiring, FIFO budget

RxFIFO raised to 0x140 for the three OUT endpoints that share it.

usbd_ctlreq.c keeps a hardcoded 4U where upstream has
USBD_MAX_NUM_INTERFACES: the Makefile's include order resolves that macro
to libDaisy's copy of usbd_conf.h, where it is 1U, which stalls every
control request above interface 1 and makes the device vanish from the
host. See docs/PITFALLS.md.

usbd_compat.h lets this tree build against both the pre- and
post-composite versions of ST's USB Device Library. That rework turned
pClass and pUserData from pointers into arrays and widened the size
parameter of USBD_LL_Transmit; no preprocessor macro distinguishes the
two generations, so the header dispatches on the fields' declared types
with _Generic and refuses an unrecognised layout outright. Without it
this file does not compile against current libDaisy.
MSG

git add usbd_audio.c usbd_audio.h
commit <<'MSG'
UAC1 class: bidirectional 24-bit audio plus MIDIStreaming

269-byte configuration descriptor, four interfaces.

The AudioControl header lists MIDIStreaming in bInCollection. Omitting it
makes usbccgp.sys self-inconsistent and Windows rejects the device with
Code 10, while macOS and Linux accept it either way.
MSG

git add fd_sinc_table.h gen_table.py usbd_audio_if.c usbd_audio_if.h
commit <<'MSG'
Transport: rings and fractional Q16 drift correction

Both rings are read at a fractional position advancing by nominally one
frame, tilted a few tens of ppm by a proportional loop on the fill level.
The USB packet is therefore always exactly 48 frames -- the Adaptive
endpoint descriptor tells the truth -- and the host/device clock
difference is absorbed by interpolation rather than by adding or dropping
a frame. No discontinuity is ever emitted.

Polyphase windowed-sinc reader, 32 taps x 128 phase rows, generated by
gen_table.py. fd_sinc_table.h is generated; do not edit it by hand.
MSG

git add main.cpp
commit <<'MSG'
Entry point: clock recovery lock, audio callback, status LEDs

CRS locks HSI48 to the host's SOF frames. LED1 tracks the record path,
LED2 the playback path; red latches until that stream restarts, so a
glitch that happened unobserved is still visible afterwards.
MSG

git add q16-drift-corrector
commit <<'MSG'
Extract the Q16 drift corrector as a standalone component

Single header, nothing included beyond stdint.h, its own MIT licence with
no scope restriction. Ships three readers and a self-test that passes both
with the sinc table and under -DQ16_NO_SINC. Redistributable on its own.
MSG

git add tests
commit <<'MSG'
Desktop tests reproducing the shipped reader's figures

tests/interp checks the shipped reader against an ideal fractional delay,
and verifies channel independence and ring-wrap equivalence.

tests/am_probe measures the amplitude modulation a continuously sweeping
read phase produces, by simulation and independently in closed form. The
two agree to the floor of what float32 and a 24-bit clamp resolve.

Neither needs hardware.
MSG

git add read_chip_rev.py read_sai_clock.py read_transport_diagnostics.py scripts
commit <<'MSG'
Host-side diagnostics over USB vendor requests

read_sai_clock.py derives the actual SAI sample rate from the live PLL
registers, which is the verification step for the libDaisy PLL3 patch:
it tests what the silicon is running, not what the source says.

soak_run.py resolves the corrector's tilt as a function of time, which a
single averaged figure over a long run hides.
MSG

git add README.md docs
commit <<'MSG'
Documentation: README, clocking, interpolation, pitfalls

docs/CLOCKING.md derives the four PLL3 constants and shows why 44.1 kHz
has no integer solution on this board: the ratio reduces to 882/625, so an
exact match would need N to be a multiple of 882, and PLL3N tops out at 512.

docs/PITFALLS.md collects the places that look wrong and are not. Each has
been "fixed" at least once, and each fix broke the device. It also covers
one symptom that looks like a firmware bug and is not: the tone on the Pod's
headphone output, which tracks the audio callback rate and the depth of the
current modulation it causes, and is absent from the samples themselves.
MSG

git add .github init_repo.sh
commit <<'MSG'
CI: run the desktop tests and check the table is reproducible

Regenerates fd_sinc_table.h from gen_table.py and fails if the result
differs from what is committed, so the README's claim that the table is
generated rather than hand-edited is checked on every push.

init_repo.sh is committed here too. It is the script that produced this
history, and it says in its own header why the history looks like an
import: keeping it visible is more honest than deleting the evidence
after running it.
MSG

echo
git log --oneline
echo
echo "Untracked files remaining (should be none):"
git status --short
